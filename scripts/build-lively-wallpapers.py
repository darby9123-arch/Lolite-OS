#!/usr/bin/env python3
"""Build Lolite's catalogue from LivelyWallpaper.app's public card metadata.

Usage: python scripts/build-lively-wallpapers.py --source-json cards.json
       --poster-dir posters --hd-headers-dir headers
The source videos stay on the publisher's CDN. No website HTML or scripts run
inside Lolite. Posters and verified HD response headers are build inputs only.
"""
import argparse
import colorsys
import json
import re
from pathlib import Path
from urllib.parse import urlparse

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'https://livelywallpaper.app/data/wallpaper-cards.json'
VERSION = 'lively-20261111'
REPLACED_BEFORE = '2026-11-11T09:14:09Z'


def media_url(value):
    url = urlparse(value)
    if url.scheme != 'https' or url.netloc != 'cdn.livelywallpaper.app':
        raise ValueError(f'Unexpected media origin: {value}')
    return value


def palette(path):
    image = Image.open(path).convert('RGB').resize((80, 45))
    quantized = image.quantize(colors=12)
    colors = quantized.getpalette()
    ranked = []
    for count, index in quantized.getcolors():
        rgb = tuple(colors[index * 3:index * 3 + 3])
        h, light, saturation = colorsys.rgb_to_hls(*(n / 255 for n in rgb))
        if saturation > .12 and .12 < light < .93:
            ranked.append((count * saturation ** 1.22, h, rgb))
    ranked.sort(reverse=True)
    if not ranked:
        return ['#%02x%02x%02x' % tuple(image.resize((1, 1)).getpixel((0, 0)))]
    primary = ranked[0]
    other = next((row for row in ranked[1:]
                  if min(abs(row[1] - primary[1]), 1 - abs(row[1] - primary[1])) > .11), primary)
    # paletteSeed uses the second vivid colour as primary.
    return ['#%02x%02x%02x' % row[2] for row in (other, primary)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-json', type=Path, required=True)
    parser.add_argument('--poster-dir', type=Path, required=True)
    parser.add_argument('--hd-headers-dir', type=Path, required=True)
    args = parser.parse_args()
    source = json.loads(args.source_json.read_text())
    entries = []
    seen = set()
    category_names = {'games': 'Games', 'anime': 'Anime', 'cars': 'Cars',
                      'nature': 'Nature', 'space': 'Space', 'art-fantasy': 'Art & Fantasy'}
    for item in source['wallpapers']:
        slug = item['slug']
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug) or slug in seen:
            raise ValueError(f'Invalid or duplicate wallpaper: {slug}')
        seen.add(slug)
        poster = media_url(item['cover_url'])
        download = media_url(item['download_url'])
        hd_headers = (args.hd_headers_dir / (slug + '.txt')).read_text().lower()
        hd_available = bool(re.search(r'http/[\d.]+ 200', hd_headers) and
                            re.search(r'content-type:\s*video/mp4', hd_headers))
        entries.append({
            'id': 'lively-' + slug, 'name': item['title'],
            'category': item['category'],
            'categories': [category_names[c] for c in item['categories'] if c in category_names],
            'tags': item['tags'], 'provider': 'LivelyWallpaper.app',
            'source': 'https://livelywallpaper.app/live-wallpapers/' + slug + '/',
            'src': poster, 'poster': poster, 'video': download,
            **({'src1080': download.rsplit('/', 1)[0] + '/hd.mp4'} if hd_available else {}),
            'preview': media_url(item['preview_url']),
            'width': item['width'], 'height': item['height'],
            'resolution': item['resolution'], 'duration': item['duration'],
            'size': item['size'], 'palette': palette(args.poster_dir / (slug + '.webp')),
        })
    if len(entries) != source['count']:
        raise ValueError('Catalogue count differs from source count')
    meta = {'version': VERSION, 'source': SOURCE, 'replacedBefore': REPLACED_BEFORE,
            'defaultId': entries[0]['id'], 'catalog': entries}
    content = ('/* Generated by scripts/build-lively-wallpapers.py. Videos stream from the source CDN. */\n'
               'window.LoliteLivelyWallpapers=Object.freeze(' + json.dumps(meta, ensure_ascii=False,
                                                                       separators=(',', ':')) + ');\n')
    (ROOT / 'core/lively-wallpapers-catalog.js').write_text(content)
    print(json.dumps({'wallpapers': len(entries), 'verifiedHD': sum('src1080' in e for e in entries),
                      'categories': sorted({e['category'] for e in entries})}))


if __name__ == '__main__':
    main()
